#!/usr/bin/env python3
"""
Write an AMS copy of a .bib file with journal names abbreviated.

Usage
-----
python bib_for_ams.py all.bib journals.csv -o all_ams.bib [--strict]

Notes
-----
The master .bib holds full journal names (as AGU requires). journals.csv has
two columns, ``full,ams``, and must list every journal name in the master --
names that are not abbreviated map to themselves -- so that a missing row is
always an error you see, not a silent pass-through.

Only the value of each ``journal`` field is rewritten; everything else is
copied byte for byte. Matching ignores whitespace differences (multi-line
values) and falls back to a case-insensitive match.

Journal names not found in journals.csv are left unchanged and listed on
stderr; with --strict they also make the exit status 1 (no output written).
"""

from pathlib import Path
import argparse
import csv
import re
import sys

GENERATED_HEADER = (
    'GENERATED by bib_for_ams.py from {src} and {csv} -- do not edit.\n'
    'Edit {src} or {csv} and rerun (make bib_for_ams).\n\n'
)


def normalize(s):
    return ' '.join(s.split())


def read_journals(csv_path):
    """Return {normalized full name: AMS abbreviation} from journals.csv."""
    table = {}
    with open(csv_path, newline='', encoding='utf-8') as f:
        for row in csv.DictReader(f):
            full, ams = normalize(row['full']), normalize(row['ams'])
            if full in table and table[full] != ams:
                raise ValueError(f'{csv_path}: conflicting rows for {full!r}')
            table[full] = ams
    return table


def journal_fields(src):
    """Yield (value_start, value_end, delim, value) for each journal field.

    delim is '{', '"' or '' (bare @string macro).  value_start/value_end span
    the value including its delimiters.
    """
    for m in re.finditer(r'(?im)^[ \t]*journal[ \t]*=[ \t]*', src):
        i = m.end()
        c = src[i]
        if c == '{':
            depth, j = 0, i
            while True:
                if src[j] == '{':
                    depth += 1
                elif src[j] == '}':
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            yield i, j + 1, '{', src[i + 1:j]
        elif c == '"':
            j = src.index('"', i + 1)
            yield i, j + 1, '"', src[i + 1:j]
        else:
            mm = re.match(r'[A-Za-z][\w:-]*', src[i:])
            yield i, i + mm.end(), '', mm.group(0)


def abbreviate(src, table):
    """Return (new_src, n_changed, unmapped) with journal names abbreviated."""
    lower = {k.lower(): v for k, v in table.items()}
    out, last, n_changed, unmapped = [], 0, 0, {}
    for i, j, delim, value in journal_fields(src):
        if delim == '':
            unmapped[f'@string macro: {value}'] = unmapped.get(f'@string macro: {value}', 0) + 1
            continue
        full = normalize(value)
        ams = table.get(full) or lower.get(full.lower())
        if ams is None:
            unmapped[full] = unmapped.get(full, 0) + 1
            continue
        if ams == value:
            continue
        close = '}' if delim == '{' else '"'
        out.append(src[last:i])
        out.append(delim + ams + close)
        last = j
        n_changed += 1
    out.append(src[last:])
    return ''.join(out), n_changed, unmapped


def main():
    parser = argparse.ArgumentParser(
        description='Abbreviate journal names in a .bib file for AMS.')
    parser.add_argument('bib', help='master .bib with full journal names')
    parser.add_argument('journals', help='journals.csv with columns full,ams')
    parser.add_argument('-o', '--output', required=True, help='output .bib')
    parser.add_argument('--strict', action='store_true',
                        help='exit 1 without writing if any journal is unmapped')
    args = parser.parse_args()

    src = Path(args.bib).read_text(encoding='utf-8')
    table = read_journals(args.journals)
    new_src, n_changed, unmapped = abbreviate(src, table)

    if unmapped:
        print(f'bib_for_ams: {len(unmapped)} journal name(s) not in '
              f'{args.journals} (left unchanged):', file=sys.stderr)
        for name, n in sorted(unmapped.items(), key=lambda kv: kv[0].lower()):
            print(f'  {n:3d}  {name}', file=sys.stderr)
        if args.strict:
            sys.exit(1)

    header = GENERATED_HEADER.format(src=Path(args.bib).name,
                                     csv=Path(args.journals).name)
    Path(args.output).write_text(header + new_src, encoding='utf-8')
    print(f'bib_for_ams: wrote {args.output} ({n_changed} journal fields '
          f'abbreviated)')


if __name__ == '__main__':
    main()
